import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { Providers } from "./providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "BidStream",
  description: "BidStream — real-time auction platform web client",
};

// Root layout stays a Server Component (no "use client" here) — it establishes
// the client-only provider boundary (§7.1) by mounting <Providers> rather than
// being one itself, so the boundary is exactly at Providers and nothing above
// it can accidentally pull a client-only module into server render (§17).
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
